import pandas as pd

# df.to_csv("eth_gas_clean_1min.csv", index=False)
df = pd.read_csv("eth_gas_clean_1min.csv")

import numpy as np

df = df.replace([np.inf, -np.inf], np.nan).dropna()

df = df[(df['avg_gas_price_gwei'] < df['avg_gas_price_gwei'].quantile(0.99)) &
        (df['avg_gas_price_gwei'] > df['avg_gas_price_gwei'].quantile(0.01))]

# Log-transform để giảm độ lệch của biến mục tiêu
df['target_log'] = np.log1p(df['avg_gas_price_gwei'])

for lag in [1, 2, 3, 5, 10]:
    df[f'gas_t-{lag}'] = df['avg_gas_price_gwei'].shift(lag)

df['gas_rolling_5'] = df['avg_gas_price_gwei'].rolling(window=5).mean()
df['gas_rolling_30'] = df['avg_gas_price_gwei'].rolling(window=30).mean()

df = df.dropna().reset_index(drop=True)

